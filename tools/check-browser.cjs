const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const {pathToFileURL}=require('node:url');
const path=require('node:path');
(async () => {
 const browser = await chromium.launch({headless:true, executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
 try {
  const page = await browser.newPage({viewport:{width:1920,height:1080}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.addInitScript(() => {
   localStorage.setItem('home.focus','app:rJeHak5zRg.Spotify');
   window.fixture={apps:[{id:'org.tizen.netflix-app',name:'Netflix'},{id:'rJeHak5zRg.Spotify',name:'Spotify'}],inputs:[{type:'HDMI',number:2}],launched:null,source:null};
   window.tizen={application:{getAppsInfo: (ok,fail)=>setTimeout(()=>fixture.failApps ? fail() : ok(fixture.apps),20),launch:(id,ok)=>{fixture.launched=id;ok();}},systeminfo:{getPropertyValue:(_,ok)=>setTimeout(()=>ok({connected:fixture.inputs}),0),addPropertyValueChangeListener:(_,fn)=>{fixture.changed=fn;return 1;}},tvwindow:{setSource:(src,ok)=>{fixture.source=src;ok();}}};
  });
  await page.goto(pathToFileURL(path.resolve(__dirname,'../app/index.html')).href);
  await page.waitForFunction(()=>document.querySelectorAll('.item').length===5);
  await page.waitForFunction(()=>!document.body.classList.contains('loading'));
  assert.equal(await page.locator('.focus .name').textContent(),'spotify');
  assert.equal(await page.locator('.name').allTextContents().then(x=>x.includes('max')),false);
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>fixture.launched),'rJeHak5zRg.Spotify');
  await page.evaluate(()=>{fixture.apps.unshift({id:'LBUAQX1exg.Hulu',name:'Hulu'});fixture.apps.push({id:'com.samsung.tv.airplay-service-2',name:'AirPlay'},{id:'org.tizen.ScreenMirroring-app-tv',name:'Screen Mirroring'});fixture.changed();});
  await page.waitForFunction(()=>document.querySelectorAll('.item').length===6);
  await page.waitForFunction(()=>document.getElementById('casting-status').textContent.includes('airplay: detected'));
  assert.equal(await page.locator('#list .name').allTextContents().then(x=>x.some(n=>/airplay|screen mirror/i.test(n))),false);
  assert.ok((await page.locator('#casting-status').textContent()).includes('live status unavailable'));
  assert.equal(await page.locator('.focus .name').textContent(),'spotify');
  for (let i=0;i<3;i++) await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('.focus .name').textContent(),'hdmi 2');
  await page.keyboard.press('Enter');
  await page.waitForFunction(()=>fixture.launched==='org.tizen.tv-viewer');
  assert.equal(await page.evaluate(()=>fixture.source.number),2);
  await page.evaluate(()=>{fixture.inputs=[];fixture.changed();});
  await page.waitForFunction(()=>!Array.from(document.querySelectorAll('h2')).some(x=>x.textContent==='inputs'));
  assert.equal(await page.locator('.focus').count(),1);
  await page.keyboard.press('Backspace');
  assert.equal(await page.locator('.focus .name').textContent(),'spotify');
  await page.waitForTimeout(500);
  await page.screenshot({path:path.resolve(__dirname,'../.local/launcher-filtered-preview.png')});
  assert.equal(await page.getByText('settings',{exact:true}).count(),0);
  for (let i=0;i<3;i++) await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('.focus .name').textContent(),'appearance: auto');
  await page.keyboard.press('ArrowRight');
  assert.equal(await page.locator('.focus .name').textContent(),'appearance: light');
  assert.equal(await page.locator('#stage').getAttribute('class'),'');
  await page.keyboard.press('Enter');
  assert.equal(await page.locator('.focus .name').textContent(),'appearance: dark');
  assert.equal(await page.locator('#stage').getAttribute('class'),'night');
  await page.keyboard.press('ArrowDown');
  assert.equal(await page.locator('.focus .name').textContent(),'samsung home');
  await page.waitForTimeout(500);
  const focused = await page.locator('.focus').boundingBox();
  const footer = await page.locator('.stamp').boundingBox();
  assert.ok(focused.y + focused.height < footer.y, 'focused row clears the footer');
  const note=await page.locator('.project-note').boundingBox();
  assert.ok(note.y>=0 && note.y+note.height<footer.y,'project note remains readable above footer');
  await page.waitForTimeout(750);
  await page.screenshot({path:path.resolve(__dirname,'../.local/launcher-bottom-preview.png')});
  await page.keyboard.press('Enter');
  assert.equal(await page.evaluate(()=>fixture.launched),'com.samsung.tv.csfs');
  await page.evaluate(()=>{fixture.failApps=true;fixture.changed();});
  await page.waitForFunction(()=>document.getElementById('casting-status').textContent.includes('status unknown'));
  await page.reload();
  await page.waitForFunction(()=>document.querySelectorAll('.item').length===5);
  assert.equal(await page.locator('#stage').getAttribute('class'),'night');
  assert.ok((await page.locator('.project-note').textContent()).includes('little sidequest'));
  assert.deepEqual(errors,[]);
  console.log('Browser passed: asynchronous discovery, missing-app filtering, focus restoration, app insertion, HDMI switching, unplugging, Back and no runtime errors.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
